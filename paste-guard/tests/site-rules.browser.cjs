
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const bundled=path.join(root,'node_modules/.cache/ms-playwright');
if(!process.env.PLAYWRIGHT_BROWSERS_PATH&&fs.existsSync(bundled))process.env.PLAYWRIGHT_BROWSERS_PATH=bundled;
const {chromium}=require('playwright');
(async()=>{
 const testRoot=path.join(root,'test-results');fs.mkdirSync(testRoot,{recursive:true});
 const profile=fs.mkdtempSync(path.join(testRoot,'site-rules-'));
 let context;let count=0;const errors=[];const passed=name=>{count++;console.log('PASS '+name);};
 try{
  context=await chromium.launchPersistentContext(profile,{channel:'chromium',headless:true,args:['--disable-extensions-except='+root,'--load-extension='+root]});
  context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  await context.route('https://*.example/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><textarea id="editor"></textarea>'}));
  for(const host of ['popup.example','settings.example'])await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:'https://'+host});
  const worker=context.serviceWorkers()[0]||await context.waitForEvent('serviceworker'),id=new URL(worker.url()).host;
  const popup=await context.newPage();await popup.goto('chrome-extension://'+id+'/popup.html');
  await popup.waitForFunction(()=>!document.querySelector('#enabled').disabled);
  // Test an actual empty list. No injected storage fixtures or mocked permissions.
  assert.equal(await popup.locator('#sites .host').count(),0);
  await popup.locator('#enabled').uncheck();
  await popup.waitForFunction(()=>document.querySelector('#status-title').textContent==='Protection off');
  await popup.locator('#site-input').fill('https://POPUP.example/some/path?test=1');
  await popup.locator('#add-form button').click();
  await popup.waitForFunction(()=>[...document.querySelectorAll('#sites .host')].some(n=>n.textContent==='popup.example'));
  assert.equal(await popup.locator('#site-input').inputValue(),'');
  assert.ok(!(await popup.locator('#message').innerText()).includes('permissions'));
  passed('popup Add saves a full URL as an Always On hostname while protection is off');
  await popup.reload();await popup.waitForFunction(()=>!document.querySelector('#enabled').disabled);
  assert.equal(await popup.locator('#sites .host').innerText(),'popup.example');
  passed('popup Always On rule persists after reload');
  await popup.locator('#site-input').fill('popup.example');await popup.locator('#add-form button').click();
  await popup.waitForFunction(()=>document.querySelector('#message').textContent.includes('already'));
  assert.equal(await popup.locator('#sites .host').count(),1);
  passed('duplicate popup additions do not duplicate the list');
  await popup.locator('#site-input').fill('ftp://bad.example');await popup.locator('#add-form button').click();
  await popup.waitForFunction(()=>document.querySelector('#message').dataset.error==='true');
  assert.equal(await popup.locator('#sites .host').count(),1);
  passed('invalid popup website is rejected without changing rules');
  const target=await context.newPage();await target.goto('https://popup.example/');
  async function pasteExpect(host,expected){
   if(target.url()!=='https://'+host+'/')await target.goto('https://'+host+'/');
   await target.bringToFront();await target.locator('#editor').fill('');await target.locator('#editor').focus();
   await target.evaluate(()=>navigator.clipboard.writeText('alice@example.com'));
   await target.keyboard.press('Control+V');
   await target.waitForFunction(expected=>document.querySelector('#editor').value===expected,expected);
  }
  await pasteExpect('popup.example','[EMAIL_1]');
  passed('website added through popup actually redacts a clipboard paste with protection off');
  const settings=await context.newPage();await settings.goto('chrome-extension://'+id+'/options.html');
  await settings.waitForFunction(()=>!document.querySelector('#fields').disabled);
  await settings.locator('#always-input').fill('https://SETTINGS.example/path');
  await settings.locator('#always-input').press('Enter');
  await settings.waitForFunction(()=>[...document.querySelectorAll('#always-sites .host')].some(n=>n.textContent==='settings.example'));
  assert.equal(await settings.locator('#always-input').inputValue(),'');
  await settings.reload();await settings.waitForFunction(()=>!document.querySelector('#fields').disabled);
  assert.equal(await settings.locator('#always-sites .host').count(),2);
  passed('settings Enter adds and persists an Always On website');
  await pasteExpect('settings.example','[EMAIL_1]');
  passed('website added through settings actually redacts with protection off');
  await settings.locator('#never-input').fill('settings.example');await settings.locator('#never-add').click();
  await settings.waitForFunction(()=>document.querySelector('#never-sites').textContent.includes('settings.example'));
  assert.equal(await settings.locator('#always-sites .host').count(),1);
  await pasteExpect('settings.example','alice@example.com');
  passed('moving Always On to Never redact removes override and stops redaction');
  await settings.locator('#always-input').fill('settings.example');await settings.locator('#always-add').click();
  await settings.waitForFunction(()=>[...document.querySelectorAll('#always-sites .host')].some(n=>n.textContent==='settings.example'));
  assert.equal(await settings.locator('#never-sites .host').count(),0);
  await pasteExpect('settings.example','[EMAIL_1]');
  passed('settings Add moves Never redact back to Always On and redaction resumes live');
  await popup.bringToFront();await popup.reload();await popup.waitForFunction(()=>!document.querySelector('#enabled').disabled);
  await popup.getByRole('button',{name:'Remove popup.example',exact:true}).click();
  await popup.waitForFunction(()=>![...document.querySelectorAll('#sites .host')].some(n=>n.textContent==='popup.example'));
  await pasteExpect('popup.example','alice@example.com');
  passed('popup removal stops redaction on that site while protection is off');
  await popup.locator('#site-input').fill('popup.example');await popup.locator('#add-form button').click();
  await popup.waitForFunction(()=>[...document.querySelectorAll('#sites .host')].some(n=>n.textContent==='popup.example'));
  await pasteExpect('popup.example','[EMAIL_1]');
  passed('popup remove then re-add works without a browser restart');
  await settings.bringToFront();await settings.reload();await settings.waitForFunction(()=>!document.querySelector('#fields').disabled);
  await settings.locator('#destination').fill('settings.example');await settings.locator('#source').fill('alice@example.com');await settings.locator('#analyze').click();
  await settings.waitForSelector('#results:not([hidden])');assert.equal(await settings.locator('#output').innerText(),'[EMAIL_1]');
  assert.equal(await settings.locator('#site-reason').innerText(),'');
  passed('preview recognizes explicit manifest permissions for the saved website');
  const saved=await worker.evaluate(async()=>chrome.storage.local.get(['sites','neverSites','enabled']));
  assert.deepEqual(saved.sites.sort(),['popup.example','settings.example']);assert.equal(saved.enabled,false);assert.deepEqual(saved.neverSites,[]);
  assert.deepEqual(errors,[]);
  console.log(count+' website-rule feature scenarios passed using the shipping manifest and real Chrome APIs.');
 }finally{
  await context?.close();
  const relative=path.relative(testRoot,path.resolve(profile));
  if(relative&&!relative.startsWith('..')&&!path.isAbsolute(relative))fs.rmSync(profile,{recursive:true,force:true});
 }
})().catch(e=>{console.error(e);process.exitCode=1;});
