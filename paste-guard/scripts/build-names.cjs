const fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto");
const {unzipSync}=require("fflate");
const root=path.resolve(__dirname,".."),vendor=path.join(root,"vendor"),lockPath=path.join(__dirname,"name-sources.json");
const sha=bytes=>crypto.createHash("sha256").update(bytes).digest("hex");
async function build(){
 const lock=JSON.parse(fs.readFileSync(lockPath,"utf8")),names=new Set(),counts={};
 for(const source of lock.sources){
  const file=path.join(root,"test-results",source.cache);
  let bytes;
  if(fs.existsSync(file))bytes=fs.readFileSync(file);
  else {const r=await fetch(source.url,{signal:AbortSignal.timeout(60000)});if(!r.ok)throw Error("Source download failed: "+source.id+" HTTP "+r.status);bytes=Buffer.from(await r.arrayBuffer());if(bytes.length>20000000)throw Error("Source too large");fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,bytes);}
  if(sha(bytes)!==source.sha256)throw Error("Source checksum changed: "+source.id+". Review the source before updating the lock.");
  let values=[];
  if(source.format==="ssa-zip"){
   for(const [name,data] of Object.entries(unzipSync(bytes))){
    if(/^yob\d{4}\.txt$/.test(name))values.push(...Buffer.from(data).toString("utf8").split(/\r?\n/).map(line=>line.split(",")[0]));
   }
  }else values=bytes.toString("utf8").split(/\r?\n/);
  let accepted=0;
  for(const raw of values){
   const name=raw.normalize("NFC").toLowerCase().trim().replace(/\u2019/g,"'");
   // Single-token entries only. Multiword names remain the language tagger's job.
   if(!/^[\p{L}\p{M}]+(?:['-][\p{L}\p{M}]+)*$/u.test(name) || Array.from(name).length<3 || name.length>60)continue;
   accepted++;names.add(name);
  }
  counts[source.id]={sourceRows:values.length,acceptedRows:accepted};
 }
 const additions=JSON.parse(fs.readFileSync(path.join(__dirname,"name-additions.json"),"utf8"));
 for(const {name} of additions)names.add(name.normalize("NFC").toLowerCase());
 const sorted=[...names].sort();
 fs.mkdirSync(vendor,{recursive:true});
 const output="// Generated by scripts/build-names.cjs. Modified: normalized, filtered and deduplicated.\n// Sources, licenses, checksums, and limitations: names.metadata.json / names.NOTICE.md.\nvar PG_NAME_DATA = "+JSON.stringify(sorted.join("\n"))+".split(\"\\n\");\n";
 fs.writeFileSync(path.join(vendor,"names.js"),output);
 fs.writeFileSync(path.join(vendor,"names.metadata.json"),JSON.stringify({version:1,uniqueNames:sorted.length,sourceSnapshot:lock.snapshot,sources:lock.sources.map(({cache,...source})=>({...source,...counts[source.id]})),localAdditions:additions,bundleSha256:sha(Buffer.from(output))},null,2)+"\n");
 console.log(JSON.stringify({uniqueNames:sorted.length,bundleBytes:Buffer.byteLength(output),counts,raghav:names.has("raghav"),stavan:names.has("stavan")}));
}
build().catch(e=>{console.error(e.message);process.exitCode=1;});
